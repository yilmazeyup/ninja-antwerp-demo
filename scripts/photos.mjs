// Writes apps/app/src/photos.ts: a require() for every picture in apps/app/assets/photos (Ninja's own photos) and
// apps/app/assets/people (stock portraits for Match), so Metro bundles them; a missing key simply has no picture.
// Run after adding or removing files.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

process.chdir(fileURLToPath(new URL('..', import.meta.url)));
const list = (dir) => (fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort() : []);
const block = (dir, rel) => list(dir).map((f) => `  '${f.replace(/\.[^.]+$/, '')}': require('${rel}/${f}'),`).join('\n');
fs.writeFileSync(
  'apps/app/src/photos.ts',
  `// Generated by scripts/photos.mjs. Ninja's own photos (assets/photos/CREDITS.md) and stock portraits for Match
// (assets/people/CREDITS.md).
/* eslint-disable @typescript-eslint/no-require-imports */
export const PHOTOS: Record<string, number> = {
${block('apps/app/assets/photos', '../assets/photos')}
};

export const PEOPLE: Record<string, number> = {
${block('apps/app/assets/people', '../assets/people')}
};

export const BRAND = {
  logo: require('../assets/brand/logo.png'),
  n: require('../assets/brand/logo-n.png'),
  leather: require('../assets/brand/leather.jpg'),
};
`,
);
console.log(`photos.ts: ${list('apps/app/assets/photos').length} photos, ${list('apps/app/assets/people').length} portraits`);
